const copyOf = (lang) => ARCADE_COPY[lang] ?? ARCADE_COPY.es

// En táctil, si el texto tiene variante propia (`<clave>Touch`, porque nombra teclas), se usa esa.
export const arcadeText = (lang, key, touch = false) => {
  const lines = copyOf(lang).lines
  return (touch && lines[`${key}Touch`]) || lines[key] || ARCADE_COPY.es.lines[key] || ''
}
export const arcadeUi = (lang) => copyOf(lang).ui
export const arcadeGame = (lang, id) => copyOf(lang).games[id] ?? ARCADE_COPY.es.games[id]

// Controles del juego según el dispositivo: los táctiles nombran el joystick y los botones A y B, no teclas.
export const arcadeControls = (lang, id, touch) => {
  const game = arcadeGame(lang, id)
  return (touch && game.controlsTouch) || game.controls
}
